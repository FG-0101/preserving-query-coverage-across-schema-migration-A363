def parse_spec(s):
    """Keywords in a category_specification string, as a sorted tuple without duplicates."""
    if not isinstance(s, str) or len(s) < 3:
        return ()
    try:
        v = json.loads(s)
        if isinstance(v, list):
            return tuple(sorted(set(x for x in v if isinstance(x, str))))
    except Exception:
        pass
    return tuple(sorted(set(re.findall(r"KEYWORD_[A-Z_]+", s))))


def load_dumps():
    """Record level reductions of the daily archives with parsed keywords."""
    fr = []
    for f in sorted(glob.glob("data/derived/dump_20*.parquet")):
        d = pd.read_parquet(f)
        fr.append(d)
    d = pd.concat(fr, ignore_index=True)
    d["d"] = pd.to_datetime(d.d)
    uniq = pd.Series(d.spec.unique())
    parsed = dict(zip(uniq, uniq.map(parse_spec)))
    d["kws"] = d.spec.map(parsed)
    d["spec_any"] = d.kws.map(lambda t: any(k != "KEYWORD_OTHER" for k in t))
    d["kw_other"] = d.kws.map(lambda t: "KEYWORD_OTHER" in t)
    # the two renamed categories are mapped to their new names, which leaves shares and entropies unchanged and merges
    # the few records filed under an old name after the cutoff with their successor
    d["c_raw"] = d.c
    d["c"] = d.c.map(lambda x: RENAMED_CAT.get(x, x))
    d["resid"] = d.c.isin(RESIDUAL)
    return d


def load_agg(months=None):
    fr = []
    for f in sorted(glob.glob("data/derived/kw_*.parquet")):
        m = f[-15:-8]
        if months is None or m in months:
            fr.append(pd.read_parquet(f))
    k = pd.concat(fr, ignore_index=True)
    k["d"] = pd.to_datetime(k.d)
    return k


def entropy_effective(counts):
    """Exponential of the Shannon entropy (nats) of a count vector, the effective number of categories."""
    c = np.asarray(counts, dtype=float)
    c = c[c > 0]
    if c.sum() == 0:
        return np.nan
    p = c / c.sum()
    return float(np.exp(-(p * np.log(p)).sum()))
